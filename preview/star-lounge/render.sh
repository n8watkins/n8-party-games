#!/usr/bin/env bash
# Round two's renders: the planet's surface and the things that pass the window, at twice round
# one's size, so they stay sharp on a phone that draws two or three pixels for one.
# The scene is the room's own (lobby/tools/blender/star-lounge.py), used as it is and not changed;
# only the size asked for is different. The pictures land in preview/star-lounge/out/ (not kept in
# git), and `node preview/star-lounge/build.mjs assets` takes them from there in place of round one's.
#   preview/star-lounge/render.sh
# Renders are heavy: each one waits for a DevGuard slot, and they run one after another.
# Do not edit this file while it runs: bash reads a script as it goes.
set -uo pipefail
here="$(cd "$(dirname "$0")" && pwd)"
scene="$(cd "$here/../../lobby/tools/blender" && pwd)"
blender="${BLENDER:-/mnt/c/Program Files/Blender Foundation/Blender 4.2/blender.exe}"
mkdir -p "$here/out"
rm -f "$here/out/.done"
run() {
  local free
  free="$(free -m | awk '/^Mem:/ {print $7}')"
  if [ "$free" -lt 5000 ]; then echo "only $free MB free: not rendering $1"; exit 1; fi
  devguard slot -- "$blender" -b -P "$(wslpath -w "$scene/star-lounge.py")" -- "$(wslpath -w "$here/out")" "$(wslpath -w "$scene")" "$@" 2>&1 | grep -E "^saved|rror:|Traceback|File \"" | grep -v "Not freed"
}
run tex-planet 4096
run sprite-liner 1280 192
run sprite-rocket 768 192
run sprite-saucer 768 192
for s in rock0 rock1 rock2; do run "sprite-$s" 512 192; done
echo done > "$here/out/.done"
