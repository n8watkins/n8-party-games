// Copies the live game's names (n8watkins/who-am-i, src/worker/content) into deck-data.js, so the
// Table plays exactly the lists whoami.n8builds.dev plays: names, aliases, difficulty, the three
// hints and the picture with its credit. Run it again after the lists change there:
//
//   node party/games/who-am-i/tools/copy-deck.mjs [path to a who-am-i checkout]
//
// It reads the checkout as it is (any branch; the commit goes in the file's header) and changes
// nothing in it. The TypeScript is bundled with esbuild (already installed here, through wrangler).
import { execFileSync } from "node:child_process";
import { mkdtempSync, writeFileSync } from "node:fs";
import { homedir, tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const repo = resolve(process.argv[2] ?? join(homedir(), "projects/games/who-am-i"));
const out = fileURLToPath(new URL("../deck-data.js", import.meta.url));
const commit = execFileSync("git", ["-C", repo, "rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();

const { build } = await import("esbuild");
const bundled = await build({
  entryPoints: [join(repo, "src/worker/content/index.ts")],
  bundle: true,
  format: "esm",
  platform: "neutral",
  write: false,
  logLevel: "silent",
});
const dir = mkdtempSync(join(tmpdir(), "who-am-i-deck-"));
const file = join(dir, "content.mjs");
writeFileSync(file, bundled.outputFiles[0].text);
const { SOURCE_PACKS, MIXED_WEIGHTS } = await import(pathToFileURL(file).href);

const lines = [];
for (const [pack, list] of Object.entries(SOURCE_PACKS)) {
  for (const i of list) {
    if (!i.active) continue;
    const p = i.picture ? [i.picture.imageUrl, i.picture.filePage, i.picture.author, i.picture.license, i.picture.free] : null;
    lines.push(`  ${JSON.stringify([i.id.slice(pack.length + 1), pack, i.canonicalName, i.difficulty, i.aliases, i.hints, p])},`);
  }
}

const text = `// GENERATED by tools/copy-deck.mjs from n8watkins/who-am-i at ${commit} (src/worker/content). Do not edit by hand:
// change the lists in that repository and run the tool again.
//
// Who Am I? names (c) 2026 Nathan Watkins, MIT licence (the who-am-i repository's LICENSE).
// Pictures are not copied: each is a thumbnail address on upload.wikimedia.org with its own credit
// (file page, author, licence, free). Real people use free photos from Wikimedia Commons; characters
// use the lead image of their own English Wikipedia article (free: false when non-free), and those
// images belong to their owners (the who-am-i README, "Pictures").
//
// SERVER ONLY: nothing in party/games is ever copied to the site (scripts/build-public.mjs).
//
// One row per name: [slug, pack, name, difficulty, aliases, [hint 1, hint 2, hint 3], picture or null],
// a picture being [thumbnail, file page, author or null, licence, free].

export const SOURCE = ${JSON.stringify({ repo: "n8watkins/who-am-i", commit, path: "src/worker/content" })};

/** Relative weights for Mixed: a pack is picked by weight, then a name from it. */
export const MIXED_WEIGHTS = ${JSON.stringify(MIXED_WEIGHTS)};

export const ROWS = [
${lines.join("\n")}
];
`;
writeFileSync(out, text);
console.log(`deck-data.js: ${lines.length} names from ${repo} at ${commit}`);
